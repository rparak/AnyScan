def _Pixels(image: QImage) -> np.ndarray:
    """
    Description:
        An image's pixels as an array.

    Args:
        (1) image [QImage(object)]: The image.

    Returns:
        (1) parameter [Matrix<uint8> HxWx4]: Its ARGB32 pixels.
    """

    image = image.convertToFormat(QImage.Format_ARGB32)
    pointer = image.constBits()
    pointer.setsize(image.byteCount())
    return np.frombuffer(pointer, np.uint8).reshape(image.height(), image.bytesPerLine() // 4, 4).copy()


def _With_Default_Font(app: QApplication, family: str, render: tp.Callable[[], QImage]) -> np.ndarray:
    """
    Description:
        Render something with the application's default font set to a family, then restore the font.

    Args:
        (1) app [QApplication(object)]: The application.
        (2) family [string]: The default font family to set.
        (3) render [Callable]: Returns the rendered image.

    Returns:
        (1) parameter [Matrix<uint8> HxWx4]: The rendered pixels.
    """

    original = app.font()
    font = QFont(original)
    font.setFamily(family)
    app.setFont(font)
    try:
        return _Pixels(render())
    finally:
        app.setFont(original)


def _Svg_Text_Image() -> QImage:
    """
    Description:
        A control: an SVG line of <text>, rendered the way Load_Svg renders the logo.

    Returns:
        (1) parameter [QImage(object)]: The render.
    """

    renderer = QSvgRenderer(QByteArray(b'<svg xmlns="http://www.w3.org/2000/svg" width="400" height="60" '
                                       b'viewBox="0 0 400 60"><text x="4" y="40" font-size="36">'
                                       b'The camera sees</text></svg>'))
    image = QImage(400, 60, QImage.Format_ARGB32_Premultiplied)
    image.fill(Qt.transparent)
    painter = QPainter(image)
    renderer.render(painter)
    painter.end()
    return image


def test_the_logo_renders_the_same_in_any_default_font(qt_app) -> None:
    """
    Description:
        The logo carries no text, only outlines, so the top bar draws the same pixels whatever the
        application's default font is. PyQt5's QtSvg ignores CSS font rules and set the old text logo in
        the default font, which clipped its tagline on Linux. The control shows the font change does
        reach text QtSvg draws, so an identical logo is not a font change that never happened.
    """

    default = QFontInfo(qt_app.font()).family()
    others = [f for f in CONST_OTHER_FONTS if QFontInfo(QFont(f)).family() == f and f != default]
    if not others:
        pytest.skip('no installed font other than the default (%s) among %s' % (default, ', '.join(CONST_OTHER_FONTS)))
    control_a = _With_Default_Font(qt_app, default, _Svg_Text_Image)
    control_b = _With_Default_Font(qt_app, others[0], _Svg_Text_Image)
    assert not np.array_equal(control_a, control_b), 'the default font did not reach QtSvg text; the test proves nothing'

    def Render_Logo() -> QImage:
        return Style.Load_Svg('anyscan-logo.svg', 54).toImage()

    logo_a = _With_Default_Font(qt_app, default, Render_Logo)
    logo_b = _With_Default_Font(qt_app, others[0], Render_Logo)
    assert logo_a.shape == logo_b.shape and np.array_equal(logo_a, logo_b), \
        'the logo renders differently under %s and %s: it still depends on a font' % (default, others[0])


def _Read(path: str) -> str:
    """
    Description:
        A file's text.

    Args:
        (1) path [string]: The file.

    Returns:
        (1) parameter [string]: Its content.
    """

    with open(path, 'r', encoding='utf-8') as handle:
        return handle.read()


def _Split_Diagram() -> tp.Tuple[str, str]:
    """
    Description:
        The diagram split into its inline logo (between the markers) and everything else.

    Returns:
        (1) parameter [Tuple<string> 1x2]: (the inline logo, the diagram without it).
    """

    diagram = _Read(CONST_DIAGRAM)
    assert diagram.count(CONST_LOGO_BEGIN) == 1 and diagram.count(CONST_LOGO_END) == 1, \
        'the diagram must carry the logo between one pair of logo:begin / logo:end markers'
    head, rest = diagram.split(CONST_LOGO_BEGIN)
    logo, tail = rest.split(CONST_LOGO_END)
    return logo, head + tail


def test_the_three_logo_copies_are_identical() -> None:
    """
    Description:
        The topbar's asset is the source file byte for byte, and the diagram's inline copy is the
        source's content unchanged. Rebuild with Example/UI/build_logo.py (it writes both files),
        then regenerate the diagram.
    """

    source = _Read(CONST_LOGO)
    assert _Read(CONST_LOGO_ASSET) == source, 'App/assets/anyscan-logo.svg differs from images/anyscan-logo.svg'
    inline, _ = _Split_Diagram()
    assert inline.strip() == source.strip(), \
        'the logo inlined in images/anyscan-architecture.svg differs from images/anyscan-logo.svg'


def _Module_Constants(path: str) -> tp.Dict[str, tp.Any]:
    """
    Description:
        A script's module-level literal constants, read from its source without importing it (the font
        builder imports fontTools at module load).

    Args:
        (1) path [string]: The script.

    Returns:
        (1) parameter [Dict]: Each module-level name assigned a literal, and its value.
    """

    constants = {}
    for node in ast.parse(open(path, encoding='utf-8').read()).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            try:
                constants[node.targets[0].id] = ast.literal_eval(node.value)
            except ValueError:
                pass
    return constants


def test_the_logo_and_the_ui_fonts_pin_the_same_inter() -> None:
    """
    Description:
        build_logo.py outlines the wordmark in the variable Inter that build_fonts.py instances the UI
        fonts from, and each script pins it on its own (each runs alone, without the other's imports).
        The two pins are one file: the same name, the same URL at the same google/fonts commit, the same
        SHA-256, so bumping one without the other fails here rather than letting the logo and the UI
        drift apart.
    """

    logo = _Module_Constants(CONST_BUILDER)
    fonts = _Module_Constants(CONST_FONT_BUILDER)
    remote, sha256 = fonts['CONST_SOURCES'][logo['CONST_FONT_NAME']]
    assert logo['CONST_FONT_URL'] == fonts['CONST_GOOGLE_FONTS'] + remote
    assert logo['CONST_FONT_SHA256'] == sha256


def test_the_diagram_draws_only_theme_tokens() -> None:
    """
    Description:
        Every colour the diagram draws, outside the inline logo, is a value of a Parameters/Theme.py
        token, so the figure reads as the same product as the application. The logo keeps its own
        palette (its magenta is not a theme token; docs/design-decisions.md); its CONST_LOGO_* tokens,
        which the top bar's live text uses, do not count here, so the diagram cannot draw in them.
    """

    tokens = {value.lower() for name, value in vars(Theme).items() if name.startswith('CONST_')
              and not name.startswith('CONST_LOGO_') and isinstance(value, str) and CONST_HEX_COLOUR.fullmatch(value)}
    _, drawing = _Split_Diagram()
    used = {colour.lower() for colour in CONST_HEX_COLOUR.findall(drawing)}
    assert used, 'the scan found no colours at all'
    assert sorted(used - tokens) == []


def _Generated() -> str:
    """
    Description:
        The diagram as the generator writes it now, from the current theme and logos.

    Returns:
        (1) parameter [string]: The SVG document.
    """

    spec = importlib.util.spec_from_file_location('architecture_diagram', CONST_GENERATOR)
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    return generator.Draw_Architecture(_Read(CONST_LOGO))


