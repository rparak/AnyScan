# System (Default)
import base64
import importlib.util
import os
import re
# Typing (Support for type hints)
import typing as tp
# Custom Lib.: AnyScan domain — the Qt-free colour palette
#   ../Parameters/Theme
import Parameters.Theme as Theme
# Custom Lib.: AnyScan UI — the console's funding band, whose logos the diagram must carry
#   ../UI/Widgets
from UI.Widgets import Funding_Row_Cls

"""
Description:
    The logo exists as three copies: images/anyscan-logo.svg (the source), App/assets/anyscan-logo.svg
    (the one the topbar renders) and the copy inlined in images/anyscan-architecture.svg. The inline
    copy is needed because the README shows the diagram through <img>, and an SVG loaded that way
    never fetches another file. Nothing else keeps three copies in step, so these tests do.

    The diagram is generated by Example/UI/architecture_diagram.py from the theme tokens; these tests
    catch a hand edit (the file is not the generator's output) and, as a second line, any colour that
    is not a token. They also hold the diagram to being linked from the README: it went 111 commits
    stale while nothing linked to it. And they hold the diagram self-contained, with every logo in it:
    under <img> a referenced file draws nothing, silently.
"""
# The repository root and the three files involved.
#   Unit [string]
CONST_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
CONST_LOGO = os.path.join(CONST_ROOT, 'images', 'anyscan-logo.svg')
CONST_LOGO_ASSET = os.path.join(CONST_ROOT, 'App', 'assets', 'anyscan-logo.svg')
CONST_DIAGRAM = os.path.join(CONST_ROOT, 'images', 'anyscan-architecture.svg')
CONST_README = os.path.join(CONST_ROOT, 'README.md')
CONST_GENERATOR = os.path.join(CONST_ROOT, 'Example', 'UI', 'architecture_diagram.py')
CONST_ASSETS = os.path.join(CONST_ROOT, 'App', 'assets')
# The PNG marks the diagram embeds: the JIC mark of the top bar, then the console's funding band.
#   Unit [List<string>]
CONST_EMBEDDED_MARKS = ['brand-jic-mute.png'] + [name for name, _ in Funding_Row_Cls.LOGOS if name is not None]
# The marker comments around the inline logo in the diagram.
#   Unit [string]
CONST_LOGO_BEGIN = '<!-- logo:begin -->'
CONST_LOGO_END = '<!-- logo:end -->'
# A hex colour as SVG writes it (#rgb or #rrggbb).
#   Unit [Pattern]
CONST_HEX_COLOUR = re.compile(r'#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![0-9A-Za-z_])')
# A reference an SVG renderer could follow: an href / xlink:href attribute, or a CSS url(...).
#   Unit [Pattern]
CONST_HREF = re.compile(r'(?:xlink:)?href\s*=\s*["\']([^"\']*)["\']')
CONST_URL = re.compile(r'url\(\s*["\']?([^"\')\s]*)')


def _Read(path: str) -> str:
    """
    Description:
        A file's text.

    Args:
        (1) path [string]: The file.

    Returns:
        (1) parameter [string]: Its content.
    """

    with open(path, 'r', encoding='utf-8') as handle:
        return handle.read()


def _Split_Diagram() -> tp.Tuple[str, str]:
    """
    Description:
        The diagram split into its inline logo (between the markers) and everything else.

    Returns:
        (1) parameter [Tuple<string> 1x2]: (the inline logo, the diagram without it).
    """

    diagram = _Read(CONST_DIAGRAM)
    assert diagram.count(CONST_LOGO_BEGIN) == 1 and diagram.count(CONST_LOGO_END) == 1, \
        'the diagram must carry the logo between one pair of logo:begin / logo:end markers'
    head, rest = diagram.split(CONST_LOGO_BEGIN)
    logo, tail = rest.split(CONST_LOGO_END)
    return logo, head + tail


def test_the_three_logo_copies_are_identical() -> None:
    """
    Description:
        The topbar's asset is the source file byte for byte, and the diagram's inline copy is the
        source's content unchanged. Edit images/anyscan-logo.svg, then copy it to the other two.
    """

    source = _Read(CONST_LOGO)
    assert _Read(CONST_LOGO_ASSET) == source, 'App/assets/anyscan-logo.svg differs from images/anyscan-logo.svg'
    inline, _ = _Split_Diagram()
    assert inline.strip() == source.strip(), \
        'the logo inlined in images/anyscan-architecture.svg differs from images/anyscan-logo.svg'


def test_the_diagram_draws_only_theme_tokens() -> None:
    """
    Description:
        Every colour the diagram draws, outside the inline logo, is a value of a Parameters/Theme.py
        token, so the figure reads as the same product as the application. The logo keeps its own
        palette, which predates the theme (docs/design-decisions.md).
    """

    tokens = {value.lower() for name, value in vars(Theme).items()
              if name.startswith('CONST_') and isinstance(value, str) and CONST_HEX_COLOUR.fullmatch(value)}
    _, drawing = _Split_Diagram()
    used = {colour.lower() for colour in CONST_HEX_COLOUR.findall(drawing)}
    assert used, 'the scan found no colours at all'
    assert sorted(used - tokens) == []


def _Generated() -> str:
    """
    Description:
        The diagram as the generator writes it now, from the current theme and logos.

    Returns:
        (1) parameter [string]: The SVG document.
    """

    spec = importlib.util.spec_from_file_location('architecture_diagram', CONST_GENERATOR)
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    return generator.Draw_Architecture(_Read(CONST_LOGO))


def test_the_diagram_is_the_generators_output() -> None:
    """
    Description:
        The committed SVG is exactly what the generator writes from the current theme and logo, so a
        hand edit, or a theme change without regenerating, fails here. Fix it by running
        python Example/UI/architecture_diagram.py, never by editing the SVG.
    """

    assert _Read(CONST_DIAGRAM) == _Generated(), \
        'images/anyscan-architecture.svg is stale or hand-edited; run python Example/UI/architecture_diagram.py'


def test_the_diagram_is_self_contained_and_carries_every_logo() -> None:
    """
    Description:
        The README shows the diagram through <img>, which fetches nothing: a linked file, an @import or
        a <link> would draw nothing, with no error. So every href and url() the generator writes is a
        #fragment or a data: URI, and every logo is inside the file — the AnyScan logo inlined, the JIC
        mark and each logo of the console's funding band as the asset's own bytes in a PNG data URI.
    """

    diagram = _Generated()
    references = CONST_HREF.findall(diagram) + CONST_URL.findall(diagram)
    assert references, 'the scan found no references at all'
    assert [r for r in references if not r.startswith(('#', 'data:'))] == []
    assert '@import' not in diagram and '<link' not in diagram
    assert _Read(CONST_LOGO).strip() in diagram, 'the AnyScan logo is not inlined'
    for name in CONST_EMBEDDED_MARKS:
        with open(os.path.join(CONST_ASSETS, name), 'rb') as handle:
            uri = 'data:image/png;base64,' + base64.b64encode(handle.read()).decode('ascii')
        assert uri in diagram, '%s is not embedded as a data URI' % name


def test_the_readme_shows_the_diagram() -> None:
    """
    Description:
        The README embeds the diagram, so it is seen and a stale one gets noticed.
    """

    assert 'images/anyscan-architecture.svg' in _Read(CONST_README)
